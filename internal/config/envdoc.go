package config

//go:generate go run ./gen -readme ../../README.md

import (
	"fmt"
	"strings"
)

// EnvTableBegin and EnvTableEnd delimit the generated table in README.md.
const (
	EnvTableBegin = "<!-- env:begin (generated by `go generate ./internal/config`; do not edit) -->"
	EnvTableEnd   = "<!-- env:end -->"
)

// EnvTable renders the documented variables as a Markdown table. README.md
// embeds it between EnvTableBegin and EnvTableEnd; a test fails when the
// two drift apart.
func EnvTable() string {
	var b strings.Builder
	b.WriteString("| Variable | Default | Description |\n|---|---|---|\n")
	for _, s := range specs {
		name := "`" + s.Name + "`"
		if s.AcceptsFile() {
			name += " / `" + s.Name + "_FILE`"
		}
		def := "—"
		if s.Default != "" {
			def = "`" + s.Default + "`"
		}
		doc := s.Doc
		if s.Secret {
			doc += " Secret: redacted in logs."
		}
		fmt.Fprintf(&b, "| %s | %s | %s |\n", name, def, strings.ReplaceAll(doc, "|", "\\|"))
	}
	return b.String()
}

// SpliceEnvTable replaces the table between the markers in a README and
// reports whether the markers were found.
func SpliceEnvTable(readme string) (string, bool) {
	start := strings.Index(readme, EnvTableBegin)
	end := strings.Index(readme, EnvTableEnd)
	if start < 0 || end < 0 || end < start {
		return readme, false
	}
	return readme[:start+len(EnvTableBegin)] + "\n" + EnvTable() + readme[end:], true
}
